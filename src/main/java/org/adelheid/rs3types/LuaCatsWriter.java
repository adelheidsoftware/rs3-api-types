package org.adelheid.rs3types;

import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.regex.Pattern;
import org.jspecify.annotations.Nullable;

/**
 * Writes an {@link ApiPage} as a LuaCATS definition file, in the forms LuaLS reads: a type whose table is a global is
 * {@code Name = {}}, one that only describes the client's objects is {@code local Name = {}}, and one without functions
 * is a class of fields alone; its functions follow, each with its description, parameters, return values and the
 * further forms of an overloaded function. Then come the page's global functions, its enumerations, and its events: a
 * payload class for each, and the {@code Event} class, whose fields are their subscriptions.
 */
final class LuaCatsWriter {

	/** The widest line of a description, after its {@code ---}. */
	private static final int WIDTH = 117;
	private static final Pattern IDENTIFIER = Pattern.compile("[A-Za-z_]\\w*");
	private static final Set<String> KEYWORDS = Set.of("and", "break", "do", "else", "elseif", "end", "false", "for",
			"function", "goto", "if", "in", "local", "nil", "not", "or", "repeat", "return", "then", "true", "until",
			"while");
	private static final Pattern SPACE = Pattern.compile(" ");
	private static final Pattern NUMBER = Pattern.compile("-?(\\d+(\\.\\d+)?|0[xX][0-9a-fA-F]+)");
	/**
	 * A description that says the value may be nil: "Returns `nil` if none is set", "Will be `nil` if", "or nil if it
	 * doesn't exist"; not "may contain `nil` values", which says so of the elements.
	 */
	private static final Pattern MAY_BE_NIL =
			Pattern.compile("(?i)\\b(returns?|will be|is|or)\\s+`?nil`?(?!\\s+values)\\b");

	private final ApiPage page;
	private final Map<String, String> aliases;
	private final List<String> reports;
	private final Map<String, String> named;
	private final Set<String> described;
	private final StringBuilder out = new StringBuilder();

	private LuaCatsWriter(ApiPage page, Map<String, String> aliases, List<String> reports,
			Map<String, String> named, Set<String> described) {
		this.page = page;
		this.aliases = aliases;
		this.reports = reports;
		this.named = named;
		this.described = described;
	}

	/**
	 * The definition file of a page.
	 *
	 * @param source the page's address, which the file's header names
	 * @param aliases the types the pages' signatures give other names, by those names
	 * @param reports where what the writer cannot express is added, as the reader adds its own
	 * @param named where each type of the API's that the file names is added, with the page that first names it
	 * @param described the types described in prose alone to write, where the page describes them: those some file
	 *     names
	 */
	static String write(ApiPage page, String source, Map<String, String> aliases, List<String> reports,
			Map<String, String> named, Set<String> described) {
		return new LuaCatsWriter(page, aliases, reports, named, described).write(source);
	}

	private String write(String source) {
		out.append("---@meta\n");
		out.append("-- Generated by rs3-api-types from ").append(source).append(";\n");
		out.append("-- regenerate it with ./gradlew generate rather than editing it.\n");
		page.types().forEach(this::type);
		page.described().forEach((name, paragraphs) -> {
			if (described.contains(name)) {
				// A type the docs describe in prose alone: its name and its description
				out.append('\n');
				description(paragraphs);
				out.append("---@class ").append(name).append('\n');
			}
		});
		page.globals().forEach(function -> function("", "", function));
		page.enums().forEach(this::enumeration);
		if (!page.events().isEmpty()) {
			events();
		}
		return out.toString();
	}

	private void type(ApiPage.TypeDoc type) {
		Boolean declared = type.global();
		boolean global = declared != null ? declared
				: type.functions().stream().anyMatch(function -> !function.colon());
		String table = global ? type.name() : lastSegment(type.name());
		out.append('\n');
		description(type.description());
		out.append("---@class ").append(type.name());
		if (!type.generics().isEmpty()) {
			out.append('<').append(String.join(", ", type.generics())).append('>');
		}
		if (type.parent() != null) {
			out.append(" : ").append(lua(type.parent()));
		}
		out.append('\n');
		for (ApiPage.PropertyDoc property : type.properties()) {
			field(property);
		}
		for (ApiPage.IndexDoc index : type.indexes()) {
			out.append("---@field [").append(lua(index.key())).append("] ").append(lua(index.value()));
			appendDescription(index.description());
			out.append('\n');
		}
		if (global) {
			out.append(table).append(" = {}\n");
		} else if (!type.functions().isEmpty()) {
			out.append("local ").append(table).append(" = {}\n");
		}
		for (ApiPage.FunctionDoc function : type.functions()) {
			function(table, type.name(), function);
		}
	}

	private void field(ApiPage.PropertyDoc property) {
		out.append("---@field ").append(key(property.name())).append(' ')
				.append(lua(maybeNil(property.type(), property.description())));
		appendDescription(property.description());
		out.append('\n');
	}

	private void function(String table, String typeName, ApiPage.FunctionDoc function) {
		Signature main = function.forms().get(0);
		out.append('\n');
		description(function.description());
		for (Signature.Param param : main.params()) {
			ApiPage.ParamDoc described = paramDoc(function, param.name());
			boolean optional = leftOut(param.type()) || (described != null && !described.required());
			out.append("---@param ").append(param.name()).append(optional && !param.name().equals("...") ? "? " : " ")
					.append(lua(present(param.type())));
			appendDescription(described == null ? "" : described.description());
			out.append('\n');
		}
		List<String> returns = returnTypes(function, main);
		checkReturns(function, main);
		for (int i = 0; i < returns.size(); i++) {
			String described = i < function.returns().size() ? function.returns().get(i).description() : "";
			out.append("---@return ").append(lua(maybeNil(returns.get(i), described)));
			if (!described.isEmpty()) {
				out.append(" # ").append(described);
			}
			out.append('\n');
		}
		for (Signature form : function.forms().subList(1, function.forms().size())) {
			out.append("---@overload ").append(overload(typeName, form)).append('\n');
		}
		List<String> names = main.params().stream().map(Signature.Param::name).toList();
		out.append("function ");
		if (!table.isEmpty()) {
			out.append(table).append(function.colon() ? ':' : '.');
		}
		out.append(function.name()).append('(').append(String.join(", ", names)).append(") end\n");
	}

	/**
	 * The types of a function's return values: its signature's, as a table below it may repeat another function's;
	 * the table's only where the signature gives none, as one written without its keyword may not.
	 */
	private static List<String> returnTypes(ApiPage.FunctionDoc function, Signature main) {
		if (!main.returns().isEmpty() || function.forms().size() > 1) {
			return main.returns();
		}
		return function.returns().stream().map(ApiPage.ReturnDoc::type).toList();
	}

	/**
	 * Reports a function whose return table gives other types than its signature, as when the table is copied from
	 * another function's; a {@code trust} fact settles which is right.
	 */
	private void checkReturns(ApiPage.FunctionDoc function, Signature main) {
		if (function.forms().size() != 1 || function.returns().size() != main.returns().size()) {
			return;
		}
		for (int i = 0; i < main.returns().size(); i++) {
			String signature = DocType.lua(main.returns().get(i), aliases, name -> { });
			String table = DocType.lua(function.returns().get(i).type(), aliases, name -> { });
			if (!withoutNil(signature).equals(withoutNil(table))) {
				reports.add(function.place() + ": " + function.name() + "'s signature returns " + main.returns().get(i)
						+ ", its table " + function.returns().get(i).type() + "; a trust fact says which is right");
				return;
			}
		}
	}

	private static String withoutNil(String type) {
		return type.endsWith("?") ? type.substring(0, type.length() - 1) : type.replace("|nil", "");
	}

	/** A type, in the docs' form or marked as LuaCATS, made optional where its description says it may be nil. */
	private static String maybeNil(String type, String description) {
		// A type corrections.txt gives is the client's, whatever the description says
		if (type.startsWith(DocType.LUA) || type.endsWith("?") || !MAY_BE_NIL.matcher(description).find()) {
			return type;
		}
		return type + "?";
	}

	/** A further form, {@code fun(self: ui.Text, horizontal: ui.AlignMode, vertical: ui.AlignMode)}. */
	private String overload(String typeName, Signature form) {
		List<String> params = new ArrayList<>();
		if (form.colon()) {
			params.add("self: " + typeName);
		}
		for (Signature.Param param : form.params()) {
			boolean optional = leftOut(param.type()) && !param.name().equals("...");
			params.add(param.name() + (optional ? "?: " : ": ") + lua(present(param.type())));
		}
		String returns = String.join(", ", form.returns().stream().map(this::lua).toList());
		return "fun(" + String.join(", ", params) + ")" + (returns.isEmpty() ? "" : ": " + returns);
	}

	/**
	 * Whether a parameter may be left out: its type ends in {@code ?}, but for a callback's, whose {@code ?} at its end
	 * is its return value's, and which marks itself after its keyword, {@code function? (self : HTTPRequest)}.
	 */
	private static boolean leftOut(String type) {
		// A lone ? is a value of any type, inputValue : ?, which must be given
		return type.startsWith("function?")
				|| (type.endsWith("?") && !type.equals("?") && !type.startsWith("function"));
	}

	/** A parameter's type without the mark that it may be left out. */
	private static String present(String type) {
		if (type.startsWith("function?")) {
			return "function" + type.substring("function?".length());
		}
		return leftOut(type) ? type.substring(0, type.length() - 1) : type;
	}

	/** The row of a function's table of parameters that describes a parameter: by name, or for varargs, by type. */
	private static ApiPage.@Nullable ParamDoc paramDoc(ApiPage.FunctionDoc function, String name) {
		return function.params().stream()
				.filter(param -> param.name().equals(name) || (name.equals("...") && param.type().equals("...")))
				.findFirst()
				.orElse(null);
	}

	/**
	 * An enumeration: an enum where the docs give its values, and otherwise a class whose fields are of its own type,
	 * which says what a value is for without inventing its number.
	 */
	private void enumeration(ApiPage.EnumDoc enumeration) {
		out.append('\n');
		description(enumeration.description());
		if (enumeration.values().stream().anyMatch(value -> value.value() == null)) {
			out.append("---@class ").append(enumeration.name()).append('\n');
			for (ApiPage.EnumValue value : enumeration.values()) {
				out.append("---@field ").append(key(value.name())).append(' ').append(enumeration.name());
				appendDescription(value.description());
				out.append('\n');
			}
			out.append(enumeration.name()).append(" = {}\n");
			return;
		}
		out.append("---@enum ").append(enumeration.name()).append('\n');
		out.append(enumeration.name()).append(" = {\n");
		for (ApiPage.EnumValue value : enumeration.values()) {
			if (!value.description().isEmpty()) {
				out.append("    ---").append(value.description()).append('\n');
			}
			out.append("    ").append(key(value.name())).append(" = ").append(literal(String.valueOf(value.value())))
					.append(",\n");
		}
		out.append("}\n");
	}

	/**
	 * The page's events: each payload a class, {@code ChatMessageEventPayload}, and the {@code Event} table, whose
	 * fields are the events' subscriptions, typed by their payload and what their callbacks return.
	 */
	private void events() {
		for (ApiPage.EventDoc event : page.events()) {
			List<ApiPage.PropertyDoc> payload = event.payload();
			if (payload != null) {
				out.append('\n');
				out.append("---The payload of the ").append(event.name()).append(" event.\n");
				out.append("---@class ").append(event.name()).append("EventPayload\n");
				payload.forEach(this::field);
			}
		}
		out.append('\n');
		description(List.of("The events the client sends plugins, by name. A function is subscribed to one with"
				+ " `Event.<name>.Subscribe(referenceName, function)`, and unsubscribed with"
				+ " `Event.<name>.Unsubscribe(referenceName)`."));
		out.append("---@class Event\n");
		for (ApiPage.EventDoc event : page.events()) {
			String payload = event.payload() == null ? "nil" : event.name() + "EventPayload";
			String returns = event.returns() == null ? "nil" : lua(event.returns());
			out.append("---@field ").append(event.name()).append(" EventSubscription<").append(payload).append(", ")
					.append(returns).append('>');
			appendDescription(event.description().isEmpty() ? "" : event.description().get(0));
			out.append('\n');
		}
		out.append("Event = {}\n");
	}

	/** A type in LuaCATS, reporting one the generator reads as {@code any} because it does not understand it. */
	private String lua(String docs) {
		if (!DocType.understands(docs, aliases)) {
			reports.add(page.path() + ": a type the generator does not understand, " + docs + "; it is any.");
		}
		return DocType.lua(docs, aliases, name -> named.putIfAbsent(name, page.path()));
	}

	/** Paragraphs as {@code ---} lines, wrapped, with an empty one between paragraphs. */
	private void description(List<String> paragraphs) {
		for (int i = 0; i < paragraphs.size(); i++) {
			if (i > 0) {
				out.append("---\n");
			}
			wrap(paragraphs.get(i)).forEach(line -> out.append("---").append(line).append('\n'));
		}
	}

	private void appendDescription(String description) {
		if (!description.isEmpty()) {
			out.append(' ').append(description);
		}
	}

	/** A paragraph's lines of at most {@link #WIDTH} characters, broken between words. */
	static List<String> wrap(String paragraph) {
		List<String> lines = new ArrayList<>();
		StringBuilder line = new StringBuilder();
		for (String word : SPACE.splitAsStream(paragraph).toList()) {
			if (!line.isEmpty() && line.length() + 1 + word.length() > WIDTH) {
				lines.add(line.toString());
				line.setLength(0);
			}
			if (!line.isEmpty()) {
				line.append(' ');
			}
			line.append(word);
		}
		if (!line.isEmpty()) {
			lines.add(line.toString());
		}
		return lines;
	}

	private static String lastSegment(String name) {
		return name.substring(name.lastIndexOf('.') + 1);
	}

	/** A field's or a table key's name, in brackets where it is no Lua name: {@code ["end"]}. */
	private static String key(String name) {
		return IDENTIFIER.matcher(name).matches() && !KEYWORDS.contains(name) ? name : "[\"" + name + "\"]";
	}

	private static String literal(String value) {
		if (NUMBER.matcher(value).matches()) {
			return value;
		}
		return "\"" + value.replace("\\", "\\\\").replace("\"", "\\\"") + "\"";
	}
}
